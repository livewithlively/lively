// web/v2/ai-login-scope.ts — #2476: «AI 로그인은 워크스페이스마다 따로» 를 말할지, 무슨 말로 할지.
//
// ── 왜 이 결정이 한 곳에 있어야 하나 ────────────────────────────────────────
// 이 사실을 말하는 자리가 둘이다 — 만들기 패널(만들기 **전**)과 온보딩 «AI 연결»(들어간 **뒤**).
//  둘 다 필요하다: 앞에서만 말하면 새 자리에서 놀란 사람에게 아무 말도 안 하는 것이고, 뒤에서만
//  말하면 만들기 직전에 알았으면 됐을 사람을 굳이 놀라게 한 뒤 설명하는 것이다.
//  그런데 판정을 두 화면이 각자 지으면 한쪽만 고쳐져 «만들 땐 말해 놓고 들어가선 안 말하는» 상태가
//  조용히 생긴다 — 그래서 판정도 문구도 여기서만 나온다.
//
// ── 언제 참인가 ─────────────────────────────────────────────────────────────
// **매니지드에서만.** 워크스페이스 하나가 테넌트 하나이고(lvly-cloud `workspaces_tenant_uq` — 1:1 이
//  관행이 아니라 제약이다) 세션 컨테이너의 `/home` 은 그 테넌트 디렉터리의 `homes/` 에서 온다
//  (lvly-cloud sessionbroker). 그래서 AI 자격이 사는 멤버 홈이 워크스페이스마다 새로 생기고, 저기서
//  이은 로그인은 여기로 따라올 길이 **구조적으로** 없다(실측 2026-08-28: «방금 로그인했는데 왜 또?»).
//
// ⚠ **셀프호스트에는 이 문장이 거짓이다.** 거긴 `org_member` 가 워크스페이스를 넘나드는 전역 신원이고
//  (src/db/tenant-column.ts IDENTITY_GLOBAL_TABLES) OS 홈이 그 멤버 id 에서만 파생되므로
//  (src/terminal/profiles.ts memberOsUser) 워크스페이스를 몇 개 만들든 같은 `/home/box_<slug>` 를 쓴다 —
//  자격이 애초에 안 사라진다. 거기서 이 말을 하면 없는 불편을 있다고 말하는 것이고, 사람은 그 말을
//  믿고 쓸데없이 다시 로그인한다. 그래서 두 함수 다 **거짓이면 빈 문자열**을 낸다(화면이 아무것도 안 그린다).
//
// ── 왜 «승계» 가 아니라 «안내» 인가 (#2476 결정) ─────────────────────────────
// 자격을 옮겨 주면 살아 있는 OAuth 사본이 디스크마다 늘어난다. 그런데 지금은 **지운 워크스페이스의
//  사본조차 안 지워지고 있다**(비-purge 디프로비저닝이 데이터 디렉터리를 `.deleted-*` 로 이름만 바꾼다).
//  위생을 고치기 전에 사본을 늘리는 건 순서가 틀렸다. 게다가 두 자리에서 같은 자격을 쓸 때 리프레시가
//  옛 사본을 죽이는지 아직 실측하지 못했다 — 죽인다면 «옛 워크스페이스가 조용히 로그아웃» 이라는
//  지금보다 나쁜 증상이 된다. #2055 로 재로그인이 이미 화면 안에서 끝나므로, 남은 것은 놀람뿐이고
//  그건 말해 주면 없어진다.
//
// ★ 문구에 «한 번만» 이 반드시 들어간다 — 「따로다」만 말하면 «여기서도 매번 묻겠구나» 로 읽혀
//  놀람이 안 가신다. 안내의 목적은 겁주기가 아니라 놀람 제거다.
//
// 이 모듈은 **의존이 없다**(순수) — 시험이 소스에서 그대로 떼어 실행한다(web 은 dist 로 안 가므로
//  import 로는 못 잡는다. web/lib/net.ts 의 wsKey 를 같은 방식으로 재는 선례가 있다).

/** 만들기 패널의 잔글씨(평문). 갈리지 않는 배포에서는 빈 문자열 — 화면이 줄 자체를 안 그린다. */
export function aiLoginScopeHint(managed: boolean): string {
  return managed ? "AI 로그인은 워크스페이스마다 따로예요 — 새 자리에서 한 번만 다시 이어 주시면 됩니다." : "";
}

/** 온보딩 «AI 연결» 로그인 화면의 안내(HTML 조각). 같은 규칙 — 아니면 빈 문자열. */
export function aiLoginScopeNote(managed: boolean): string {
  return managed
    ? '<p class="ob-note">AI 로그인은 <b>워크스페이스마다 따로</b>예요. 다른 워크스페이스에서 이미 이으셨더라도 여기선 한 번 더 필요합니다 — 지금 한 번만 이어 두면 이 워크스페이스에서는 계속 유지돼요.</p>'
    : "";
}
