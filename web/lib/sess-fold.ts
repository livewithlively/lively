// lib/sess-fold.ts — 프로젝트 폴더 아래 **무엇을 그대로 세우고 무엇을 접을지**의 잣대 한 자리 (#762).
//
//  원준 2026-09-05 신고: "폴더를 펼쳐도 그 세션이 안 보였다 — 프로젝트 안에 들어가서 굳이굳이 찾아서 열었다."
//  원인은 권한도 목록 API 도 아니었다. 사이드바가 **도는 세션만** 폴더에 세우고 멈춘 것은 전부 「지난 세션 n」
//  한 줄 뒤로 접었기 때문이다. 어제 하던 일은 tmux 가 죽는 순간 소리 없이 그 뒤로 내려갔다
//  (실측: SNUCOM BUILD 폴더에 지난 세션 20개가 그 한 줄 뒤에 있었다).
//
//  ⚠ 「지난 세션」을 없애는 것은 답이 아니다 — 그 묶음은 원준 2026-08-24 지시("난 연 적이 없는데 지멋대로
//   펼쳐져 있어")로 **기본 접힘 · 기억 안 함**이 된 것이고, 배경을 본문 위로 올리면 그 신고가 되돌아온다.
//   가를 것은 '멈췄나'가 아니라 **'아직 오늘 일감인가'** 다: 멈춘 지 하루가 안 된 것은 배경이 아니다.
//
//  잎 모듈인 이유는 find.ts 와 같다 — 이 잣대가 화면 코드 안에 인라인으로 있으면 시험할 데가 없고,
//  그래서 조용히 깨진다. 실제로 이번 신고가 그 종류였다.

/** 멈춘 지 이만큼 안 됐으면 '지금 일감'이다. 하루 — 어제 자정 넘어 하던 일이 오늘 아침에도 폴더에 남는 길이. */
export const WARM_MS = 24 * 60 * 60 * 1000;

/** 이 세션이 '지금 일감'인가 — 도는 중이거나, 멈췄어도 하루가 안 지났으면 참. */
export function isWarmSess(s: { live?: boolean; alive?: boolean; lastSeen?: number }, now: number): boolean {
  if (s.live && s.alive) return true;                       // 도는 중 — 언제나 본문
  const t = Number(s.lastSeen || 0);
  return t > 0 && now - t < WARM_MS;
}

/**
 * 폴더 아래 줄을 둘로 가른다.
 *  - `now`  = 그대로 서는 것(도는 것 + 방금 멈춘 것). 한 목록이고 상한도 **하나**다 — 둘로 나눠 세면
 *             폴더가 상한의 두 배까지 자란다.
 *  - `cold` = 「지난 세션 n」 뒤로 접히는 것(하루 넘게 조용한 것).
 * 들어온 순서를 그대로 지킨다 — 정렬은 부르는 쪽의 몫이다(도는 것은 상태순, 멈춘 것은 최근순).
 */
export function splitFolderRows<T extends { live?: boolean; alive?: boolean; lastSeen?: number }>(
  live: T[], past: T[], now: number,
): { now: T[]; cold: T[] } {
  const warm = past.filter((s) => isWarmSess(s, now));
  const cold = past.filter((s) => !isWarmSess(s, now));
  return { now: [...live, ...warm], cold };
}

// ── 홈 목록이 **아예 받느냐**의 자 — 위 isWarmSess 와 묻는 것이 다르다 ─────────────────
//  isWarmSess 는 «프로젝트 폴더 **안에서** 접느냐»를 묻는다(목록이 작다 → 하루 창이면 충분).
//  여기서 묻는 것은 «홈 목록이 그 줄을 **세우느냐**»다. 홈은 '오늘 붙들고 있는 것'이고 명부가 아니라서
//  (내 세션 320건 중 314건이 지난 세션이다) 하루 창을 그대로 쓰면 목록이 명부가 된다 — 실측으로 헤비 유저
//  한 사람이 25줄에서 77줄이 됐다. 그래서 이 축은 **날짜**로 자른다.
//
//  ⚠ 다만 달력 자정으로 자르면 **새벽에 일하는 사람의 목록이 통째로 빈다**. 원준 2026-09-05 01:20 실측:
//   그 시각 그 사람의 멈춘 세션이 홈 목록에 **0줄**이었고, 찾던 「투어 영상 제작」은 최신에서 2번째였다.
//   자정을 막 넘겼다고 해서 어젯밤에 하던 일이 남의 일이 되지는 않는다 — 밤은 아직 안 끝났다.

/** 하루가 시작한다고 치는 시각(그 지역 시간). 새벽 5시 — 이 앞은 아직 '어젯밤'이다. */
export const DAY_START_HOUR = 5;

/**
 * '오늘 일감'의 시작 시각 — **자정과 '가장 최근 새벽 5시' 중 이른 쪽**.
 *  · 낮(05:00 이후)이면 그냥 자정이다 — 종전과 **같다**(낮에 목록이 길어지지 않는다).
 *  · 새벽(00:00~04:59)이면 어제 05:00 까지 거슬러 받는다 — 그 시간에 일하는 사람의 '오늘'은 아직 어젯밤이다.
 *  둘 중 **이른 쪽**이라 어느 시각에도 종전보다 좁아지지 않는다(새벽 2시에 쓴 세션이 아침에 사라지지 않는다).
 */
export function workDayStart(now: number): number {
  const d = new Date(now);
  const midnight = new Date(d.getFullYear(), d.getMonth(), d.getDate()).getTime();
  const five = midnight + DAY_START_HOUR * 3600_000;
  return now < five ? five - 86_400_000 : midnight;
}

// ── 홈 목록 **프로젝트 카드 안**의 자 — 위 두 자와 또 묻는 것이 다르다 ─────────────────
//  isWarmSess 는 «폴더 안에서 접느냐»(하루 창) · workDayStart 는 «홈이 그 줄을 받느냐»(오늘 창)를 묻는다.
//  여기서 묻는 것은 «홈 카드를 폈을 때 그 줄이 곧바로 보이느냐»다 — 받은 줄은 이미 **전부 오늘 것**이므로
//  시각이 아니라 **끝났나(past)** 하나로 가른다(원준 2026-09-09 안 C: "지난 세션이 되어도 구분이 안 된다").

/** 카드 안 한 줄이 이 판정에 내놓는 것. 홈이 행을 세울 때 붙이는 표식 둘이다(web/v2/main.ts). */
export interface CardRow {
  /** 끝난 세션인가(도는 박스가 없다). */
  past?: boolean;
  /** 지금 보고 있는 화면인가. */
  active?: boolean;
}

/**
 * 카드 안 줄을 둘로 가른다.
 *  - `now`    = 카드를 펴면 **그대로 보이는** 줄
 *  - `folded` = 「지난 세션 n」 한 줄 뒤로 접히는 줄
 *  - `open`   = 그 접힘이 지금 열려 있나
 *
 * ★ **접히지 않을 앞면이 없으면 접지 않는다**(원준 2026-09-09: "지난 세션밖에 없어지면 어케돼?").
 *  접힘은 «배경이 본문을 덮지 않게» 하는 장치다. 본문이 없으면 덮을 것이 없고, 그때 접으면 카드에
 *  뚜껑만 남아 **오늘 한 일이 두 번 클릭 뒤로 숨는다** — 「폴더를 펼쳐도 그 세션이 안 보였다」(#762·#1808)로
 *  이미 한 번 고친 그 증상이다. 그래서 그 카드에서는 줄이 들어온 순서 그대로 선다(행의 흐린 톤이 대신 말한다).
 *
 * 들어온 순서를 지킨다 — 각 자리 안의 앞뒤도, 접지 않을 때의 전체 순서도 부르는 쪽이 준 그대로다.
 */
export function foldCardRows<T extends CardRow>(
  rows: T[],
  o: { searching?: boolean; opened?: boolean } = {},
): { now: T[]; folded: T[]; open: boolean } {
  const now: T[] = [], folded: T[] = [];
  for (const r of rows) (r.past ? folded : now).push(r);
  //  접을 것이 없거나(끝난 줄 0) 접히지 않을 앞면이 없으면(도는 줄 0) 접힘 자체를 만들지 않는다.
  if (!folded.length || !now.length) return { now: rows, folded: [], open: false };
  return {
    now, folded,
    //  ⚠ **보고 있는 세션은 접히더라도 보여야 한다** — 보고 있는 화면이 목록에 없으면 그게 고장이다
    //   (main.ts ③ force 가 지키는 그 한 줄). 검색도 같다: 찾으려고 건 렌즈를 접힘이 가리면 안 된다(#1719).
    open: !!o.searching || !!o.opened || folded.some((r) => r.active),
  };
}

// ── 카드 안 「지난 세션」이 **시간이 지나도 안 줄게** (#3778 4판, 원준 2026-09-12) ─────────────
//
//  신고: "내가 쓰다가 사라진 세션이 엄청 많은데 지난 세션이 1개밖에 없다. 기준 없이 사라지는 느낌이다."
//
//  ★ 세 가지가 겹쳐 있었다(전부 실측·코드 확인):
//   ① **치운 세션은 「지난 세션」으로 안 갔다.** 그냥 목록에서 없어졌다(sess-visibility 규칙 ②
//      «치움 → 안 선다»). 사람의 모델은 «치우면 지난 세션 안으로 들어간다» 인데 그런 경로가 없었다.
//   ② **홈 카드는 오늘 것만 받았다.** 어제 이전의 지난 세션은 카드에 오지도 않아 접힘 **숫자에도** 안 잡혔다.
//   ③ **«내가 그 탭을 닫았나» 가 하루 뒤 생사를 갈랐다.** 안 닫았으면(kept) 어제 것도 서고, 닫았으면 안 선다.
//      사람은 그걸 기억하지 않는다 — 그래서 어떤 건 남고 어떤 건 사라지는 것처럼 보였다.
//
//  ⇒ **서 있는 줄의 규칙은 안 건드린다.** 홈이 «오늘 붙들고 있는 것» 이라는 취지(#2208·#3855)는 그대로다.
//   대신 **접힘 안쪽만 전량으로 넓힌다.** 접힘은 카드당 **한 줄**이라 목록을 길게 만들지 않는다 —
//   «홈이 명부가 되면 안 된다» 가 걱정한 것은 줄이 늘어나는 것이었고, 접힌 숫자는 줄을 안 늘린다.
//   그러면 홈 카드와 [AI 세션] 카드가 **같은 내용**이 된다(원준: "둘이 달라질 이유가 있나").

/** 이 판정이 세션에게 묻는 것 전부. 한 세션이 여러 이름으로 불리므로(박스 id · 대화 uuid · 옛 박스 id) 셋 다 본다. */
export interface PastRowLike {
  id: string;
  projectId?: number | null;
  /** views.ts 의 두 칸 — 도는 세션은 둘 다 참이다. */
  live?: boolean;
  alive?: boolean;
  lastSeen?: number;
  /** 휴지통 표식 — **칸 이름이 `trashedAt` 인 것이 핵심이다**(views.ts `isTrashedSess = !!s.trashedAt`).
   *  4판은 이 자리를 `trashed?: boolean` 으로 뒀는데 **Sess 에 없는 칸**이라 실제 자료에서 한 번도 안 걸렸다 —
   *  즉 휴지통 세션이 카드 접힘 안에 그대로 섰다(#1851 이 막으려던 «되돌리기 전에 열린다»). 테스트는
   *  `{trashed:true}` 객체를 손으로 지어 넣어 그 구멍을 못 봤다. 자료형과 **같은 이름**을 쓰는 것이 고침이다. */
  trashedAt?: string | null;
  logId?: string | null;
  altIds?: string[];
}

/**
 * 한 프로젝트 카드의 **접힘 안에 들어갈 지난 세션**.
 *
 *  · `shown` — 이미 그 카드에 **서 있는** 줄의 세션 id. 같은 세션을 두 번 그리지 않는다.
 *  · `cap`   — 펼쳤을 때 그릴 상한. 넘는 만큼은 `total` 로만 말하고 «외 n개» 로 프로젝트 화면에 넘긴다.
 *  · `keepLive` — 도는 세션도 담는다. **앞면이 하나도 없는 카드에서만** 켠다(#3778 5판) — 아래 ⚠ 참조.
 *
 *  ⚠ **날짜로 자르지 않는다.** 이 목록이 시간이 지나도 안 줄어드는 것이 이 함수의 존재 이유다.
 *  ⚠ 휴지통 것은 뺀다 — 휴지통은 별도 화면이고, 거기 있는 것을 여기 세우면 되돌리기 전에 열리게 된다(#1851).
 *  ⚠ 도는 세션은 기본적으로 뺀다 — 그건 접힘이 아니라 **앞면**에 설 것이기 때문이다. 그런데 **앞면이 하나도
 *   없는 카드**에서는 그 이유가 사라진다: 치운 도는 세션(sess-visibility 규칙 ② 가 규칙 ③ live 보다 먼저다)은
 *   줄로도 안 서고 접힘에서도 빠져 **어디에도 없다**. 그 카드가 통째로 비어 버린다. `keepLive` 가 그 구멍을 막는다
 *   (foldCardRows 의 "본면이 없으면 덮을 것이 없다" 와 같은 규율).
 *  ⚠ 주인으로 거르지 않는다 — [AI 세션] 구역과 같은 집합이어야 «둘이 같다» 가 참이 된다. 남의 세션은
 *   행이 주인 얼굴을 달고 서므로(#2026) 누구 것인지는 줄이 스스로 말한다.
 */
export function projectPastRows<T extends PastRowLike>(
  all: readonly T[] | null | undefined,
  projectId: number,
  shown: ReadonlySet<string>,
  cap: number,
  o: { keepLive?: boolean } = {},
): { rows: T[]; total: number } {
  if (!projectId) return { rows: [], total: 0 };
  const hit: T[] = [];
  for (const s of all || []) {
    if (!s || Number(s.projectId || 0) !== projectId) continue;
    if (s.live && s.alive && !o.keepLive) continue;        // 도는 세션은 접힘이 아니라 앞면이다(앞면이 있을 때만)
    if (s.trashedAt) continue;
    const names = [s.id, s.logId || '', ...(s.altIds || [])].filter(Boolean);
    if (names.some((n) => shown.has(String(n)))) continue;  // 이미 서 있다
    hit.push(s);
  }
  hit.sort((a, b) => (Number(b.lastSeen) || 0) - (Number(a.lastSeen) || 0));
  return { rows: cap > 0 ? hit.slice(0, cap) : hit, total: hit.length };
}


// ── 「어디에도 없는 세션」을 0 으로 (#3778 5판, 원준 2026-09-12) ──────────────────────
//
//  신고: "사이드바에서 아예 어떻게도 볼 수 없는 숨겨져 있는 세션이 존재하는 것 자체가 말이 안 된다.
//   그럼 그거 쓰려면 프로젝트까지 들어가서 지금 안 열린 세션 찾아서 다시 열어야 하잖아."
//
//  실측(2026-09-12, 원준님 계정): **내 세션 190개 중 33개**가 홈 사이드바 어디에도 없었다.
//  그 33개는 **카드가 안 서는 프로젝트 24개** 안에 있었다 — 4판이 접힘 안쪽을 전량으로 넓혔지만,
//  그건 «카드가 이미 서 있을 때» 의 이야기였다. 카드 자체가 없으면 넓힌 접힘도 그릴 자리가 없다.
//
//  ★ 원인은 규칙 하나가 아니라 **서로 다른 시기의 규칙 셋이 같은 자리를 다른 기준으로 판정**한 것이다:
//   ① 7/23 «어느 탭에 열려 있으면 온라인» — 탭 줄은 8/25 에 없어졌는데 판정만 남았다
//   ② 8/27 «홈은 오늘 붙들고 있는 것» — 날짜로 자르니 어제 이전 프로젝트가 통째로 빠진다
//   ③ 9/10 «내가 안 닫은 세션은 남긴다» — 닫는 길이 × 하나뿐이라 한쪽으로만 쌓인다
//  세 기준 중 어느 것도 화면에 안 나타난다. 그래서 «기준 없이 사라진다» 로 읽혔다.
//
//  ⇒ **기준을 하나 더 얹지 않는다. 바닥을 바꾼다.** 홈 목록의 바닥을 «오늘» 이 아니라 **프로젝트**로 둔다:
//   내 세션이 있는 프로젝트는 전부 카드를 갖고, 그 카드가 그 프로젝트의 세션 전량을 진다.
//   그러면 «안 보이는 세션» 이 정의상 0 이 된다.
//
//  ⚠ 그래도 **서 있는 줄의 규칙은 그대로다**(#2208·#3855 의 취지 — 홈이 명부가 되면 안 된다).
//   새로 서는 카드는 **접힌 한 줄**이라 목록이 줄 단위로 길어지지 않는다. 원준님 계정에서 24줄이 는다.
//  ⚠ 새 묶음 이름을 만들지 않는다 — 날짜 어휘(hold-rules dayGroup)는 이미 바닥이 없어서, 한 달 전
//   프로젝트는 「8월 13일」 묶음에 그대로 선다. 목록의 문법이 한 벌 그대로여야 두 축으로 안 읽힌다.

/** 카드를 **새로 세울지** 묻는 판정이 세션에게 묻는 것 전부. */
export interface RestCardLike {
  projectId?: number | null;
  lastSeen?: number;
  trashedAt?: string | null;
  /** 내 세션인가(views.ts Sess.owned). */
  owned?: boolean;
}

/** 줄이 하나도 없어서 새로 세우는 카드 한 장. */
export interface RestCard {
  /** 프로젝트 id. */
  id: number;
  /** 그 프로젝트에서 가장 최근에 쓴 시각 — 날짜 묶음 이름과 순서를 이 값이 정한다. */
  at: number;
  /** 그 카드가 지는 내 세션 수(접힘에 「지난 세션 n」으로 나올 값의 하한). */
  n: number;
}

/**
 * **줄이 하나도 안 선 프로젝트**의 카드를 세운다 — 홈 목록에서 안 보이는 세션을 0 으로 만드는 자리.
 *
 *  · `hasCard` — 이미 카드가 선 프로젝트 id. 그 프로젝트는 건드리지 않는다(같은 카드를 두 번 세우지 않는다).
 *
 *  ⚠ **날짜로 자르지 않는다** — 이 목록에 바닥이 없는 것이 이 함수의 존재 이유다(4판 projectPastRows 와 같은 규율).
 *  ⚠ 휴지통은 뺀다 — 휴지통은 별도 화면이고, 거기 있는 것으로 카드를 세우면 되돌리기 전에 열린다(#1851).
 *  ⚠ **내 세션만 센다.** 이미 선 카드 **안**은 남의 세션도 담지만(projectPastRows — 행이 주인 얼굴을 달고 선다),
 *   카드를 **새로 세우는** 이유는 내 일이어야 한다. 아니면 동료만 일하는 프로젝트가 내 홈에 카드로 쌓인다.
 *  ⚠ 도는 세션도 센다. 도는 세션은 보통 ① 이 줄로 세우므로 여기 안 오지만, 이 함수의 약속은
 *   «내 세션이 있으면 카드가 있다» 이지 «끝난 세션이 있으면» 이 아니다 — 예외를 두면 구멍이 다시 생긴다.
 */
export function restProjectCards<T extends RestCardLike>(
  all: readonly T[] | null | undefined,
  hasCard: ReadonlySet<number>,
): RestCard[] {
  const by = new Map<number, RestCard>();
  for (const s of all || []) {
    if (!s || !s.owned || s.trashedAt) continue;
    const id = Number(s.projectId || 0);
    if (!id || hasCard.has(id)) continue;
    const at = Number(s.lastSeen) || 0;
    const c = by.get(id);
    if (c) { c.n++; if (at > c.at) c.at = at; }
    else by.set(id, { id, at, n: 1 });
  }
  return [...by.values()].sort((a, b) => b.at - a.at);
}
