export interface GroupDef {
  /** 저장되는 key(`g1`·`g2`…) — 사람이 이름을 바꿔도 이 값은 안 바뀐다. */
  key: string;
  /** 화면 이름. 사람이 고칠 수 있다. */
  name: string;
  /** 한 줄 뜻 — 화면 설명과 리브 지시문에 그대로 쓴다. */
  hint: string;
}

export interface GroupSet {
  /** 화면 순서대로의 칸(3~5). */
  groups: GroupDef[];
  /** 판정 질문 — 칸 이름을 «» 로 전부 부른다. */
  ask: string;
  /** 받침 칸(key) — 그 자리의 본업 칸. 고루 걸치는 카테고리·종류로 나눈 서랍·이름으로 모르는 카테고리가 간다. */
  fallback: string;
  /** 경계 예시(선택) — 리브 지시문에 함께 실린다. */
  note?: string;
  /** 서버 이름 규칙의 전순서(key, 앞이 이긴다). groups 의 key 를 빠짐없이 한 번씩. */
  order: string[];
  /** 서버 이름 규칙 — 칸 key → 카테고리 이름에 이 낱말이 있으면 그 칸. 칸 이름의 낱말도 자동으로 들어간다. **정밀도 우선.**
   *  ⚠ 전순서 맨 끝 칸이 받침 칸이면 그 칸 낱말은 판정을 바꾸지 않는다(안 맞아도 받침이다) — 그 칸이 무엇을 받는지 적어 둔 문서다. */
  words: Record<string, RegExp>;
  /** 자동으로 더하지 않은 칸 이름 낱말(두 칸이 같이 쓰거나, 그 자리에서 너무 넓은 말). */
  nameWordSkips: string[];
}

type Spec = {
  groups: Array<[name: string, hint: string, words: RegExp]>;
  /** 칸 이름의 낱말을 서버 낱말에 더하나(기본 true). «누가 만들었나» 보편 축은 끈다 — 칸 이름이 «자료»·«규정»·«협업» 같은
   *  일반명사라 낱말로 쓰면 «사내 규정»·«강의 자료»·«그 밖의 자료» 가 바깥 칸으로 간다(#1812 검증 — 종전 판정과 어긋났다). */
  nameWords?: boolean;
  /** 이 집합에서만 자동으로 더하지 않을 칸 이름 낱말(그 자리에선 너무 넓은 말 — 교원의 «업무»). */
  skipNameWords?: string[];
  ask: string;
  fallback: string;         // 이름으로 적는다(읽기 쉽게) — key 로 바꿔 담는다
  note?: string;
  order: string[];          // 이름
};

/** 이름의 낱말(2자 이상) — «캠페인·콘텐츠» → 캠페인, 콘텐츠. */
export const nameTokens = (name: string): string[] =>
  name.split(/[·・ㆍ•‧∙,/&+_|\-\s()]+/).map((t) => t.trim()).filter((t) => t.length >= 2);

const esc = (t: string) => t.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

/** 칸 이름 낱말 중 다른 낱말 속에 흔히 드는 것 — 이름에서 자동으로 더할 때도 같은 경계를 건다(«제조사» 의 «조사» · «위험성평가» 의 «평가»). */
const TOKEN_GUARD: Record<string, string> = { "조사": "(?<!제)조사", "평가": "(?<!위험성 ?)평가", "인사": "인사(?!이트)" };

/** 서버 낱말 정규식을 다듬는다 — 영문 약어는 낱말 경계로(«IR» 이 AIRFLOW 를 잡지 않게)·대소문자 무시, 칸 이름의 낱말을 더한다. */
const ASCII_ALT = /^(?:[A-Za-z0-9]|\\\/)+$/;   // 영문·숫자(«A\/B» 처럼 이스케이프한 / 포함)만으로 된 대안 — 낱말 경계를 씌운다
const asciiBound = (a: string) => `(?<![A-Za-z0-9])${a}(?![A-Za-z0-9])`;

/** 정규식 원문을 **맨 바깥** «|» 로만 가른다 — 괄호·문자 클래스 안의 «|»(«광고(?! ?(소재|원고))»)는 그대로 둔다. */
export function splitTop(src: string): string[] {
  const out: string[] = [];
  let depth = 0, inClass = false, cur = "";
  for (let i = 0; i < src.length; i++) {
    const c = src[i];
    if (c === "\\") { cur += c + (src[i + 1] ?? ""); i++; continue; }
    if (inClass) { if (c === "]") inClass = false; cur += c; continue; }
    if (c === "[") inClass = true;
    else if (c === "(") depth++;
    else if (c === ")") depth--;
    else if (c === "|" && depth === 0) { out.push(cur); cur = ""; continue; }
    cur += c;
  }
  out.push(cur);
  return out;
}

function wordRe(re: RegExp | null, name: string, withName = true, skip: ReadonlySet<string> = new Set()): RegExp {
  const alts = re ? splitTop(re.source).map((a) => (ASCII_ALT.test(a) ? asciiBound(a) : a)) : [];
  if (withName) for (const t of nameTokens(name)) {
    if (skip.has(t)) continue;
    alts.push(Object.hasOwn(TOKEN_GUARD, t) ? TOKEN_GUARD[t] : (ASCII_ALT.test(t) ? asciiBound(esc(t)) : esc(t)));
  }
  return new RegExp(alts.length ? alts.join("|") : "(?!)", "i");
}

/** 칸 이름만으로 만든 낱말 정규식 — 사람이 고치거나 더한 칸에 쓴다(서버 낱말과 같은 경계·대소문자 규칙). */
const nameRe = (name: string): RegExp => wordRe(null, name);

/** 이름으로 적은 명세 → key(g1…) 로 담은 집합. 이름 오타는 여기서 바로 터진다(모듈 로드 시점). */
function SET(spec: Spec): GroupSet {
  const groups = spec.groups.map(([name, hint], i) => ({ key: `g${i + 1}`, name, hint }));
  //  두 칸 이상이 같이 쓰는 이름 낱말(«연구 과제»·«과제 행정» 의 «과제»)은 자동으로 더하지 않는다 — 더하면 전순서 앞 칸이
  //   그 낱말을 통째로 가져간다(#1812 검증: «국책과제 A» 가 과제 행정으로).
  const all = groups.flatMap((g) => nameTokens(g.name));
  const shared = new Set([...all.filter((t, i) => all.indexOf(t) !== i), ...(spec.skipNameWords ?? [])]);
  const keyOf = (name: string): string => {
    const g = groups.find((x) => x.name === name);
    if (!g) throw new Error(`category-groups: 「${name}」 칸이 없다(${groups.map((x) => x.name).join(" / ")})`);
    return g.key;
  };
  return {
    groups,
    ask: spec.ask,
    fallback: keyOf(spec.fallback),
    ...(spec.note ? { note: spec.note } : {}),
    order: spec.order.map(keyOf),
    words: Object.fromEntries(spec.groups.map(([name, , w], i) => [`g${i + 1}`, wordRe(w, name, spec.nameWords !== false, shared)])),
    nameWordSkips: [...shared],
  };
}

