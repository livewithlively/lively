function jobByKeyword(job: string, stage: string): string | undefined {
  for (const [re, to] of JOB_KEYWORDS) {
    if (!re.test(job)) continue;
    const label = typeof to === "string" ? to : own(to, stage);
    if (label) return label;
  }
  return undefined;
}

//  라우팅 표의 목적지는 전부 GROUP_SETS 에 있어야 한다 — 오타는 조용히 default 로 떨어지므로 모듈 로드 시점에 던진다.
for (const [from, to] of [
  ...Object.entries(JOB_ALIAS), ...Object.entries(STAGE_FALLBACK), ...Object.entries(FREE_TEXT_FALLBACK),
  ...JOB_KEYWORDS.flatMap(([re, t]) => (typeof t === "string" ? [[re.source, t]] : Object.entries(t).map(([st, v]) => [`${re.source}@${st}`, v]))),
] as Array<[string, string]>) {
  if (!Object.hasOwn(GROUP_SETS, to)) throw new Error(`category-groups: 「${from}」 → 「${to}」 집합이 없다`);
}

/** 표 조회 — **자기 키만**. «constructor»·«__proto__» 같은 답이 Object.prototype 을 집어 오면 뒤에서 .groups 가 터진다. */
const own = <T>(table: Record<string, T>, k: string): T | undefined => (Object.hasOwn(table, k) ? table[k] : undefined);

/** 이 자리의 집합 — 2단 답이 먼저(라벨 → 별칭 → 직접 적은 답의 낱말), 없으면 1단(무대), 그래도 없으면 default. 어느 경로로도 빈손이 없다. */
export function groupSetDefFor(stage?: string | null, job?: string | null): GroupSet {
  const j = String(job ?? "").trim();
  const st = String(stage ?? "").trim();
  const byJob = j ? own(GROUP_SETS, j) ?? own(GROUP_SETS, own(JOB_ALIAS, j) ?? "") ?? own(GROUP_SETS, jobByKeyword(j, st) ?? "") : undefined;
  if (byJob) return byJob;
  if (j) { const free = own(GROUP_SETS, own(FREE_TEXT_FALLBACK, st) ?? ""); if (free) return free; }
  const byStage = own(GROUP_SETS, own(STAGE_FALLBACK, st) ?? "");
  return byStage ?? GROUP_SETS.default;
}

/** 이 자리가 처음 받을 칸들(화면 순서). */
export function groupSetFor(stage?: string | null, job?: string | null): GroupDef[] {
  return groupSetDefFor(stage, job).groups;
}

const ALL_SETS: GroupSet[] = [...new Set(Object.values(GROUP_SETS)), ...LEGACY_SETS];
const sameName = (a: string, b: string) => a.trim() === b.trim();

/** 이 워크스페이스에 지금 있는 묶음이 어느 집합 **그대로**인가 — key·이름이 전부 같을 때만(화면 순서는 무관). 고쳤으면 null.
 *  리브 지시문의 «가르는 기준» 문장을 고르는 데 쓴다 — 이름이 하나라도 다르면 그 집합의 문장이 거짓말이 된다. */
export function setMatching(groups: ReadonlyArray<{ key: string; name: string }>): GroupSet | null {
  if (!groups.length) return null;
  for (const def of ALL_SETS) {
    if (def.groups.length !== groups.length) continue;
    if (def.groups.every((d) => groups.some((g) => g.key === d.key && sameName(g.name, d.name)))) return def;
  }
  return null;
}

type LiveGroup = { key: string; name: string; hint?: string | null };

/** 순위 튜플의 사전식 비교 — 앞 자리가 크면 이긴다. */
const lexGreater = (a: readonly number[], b: readonly number[]): boolean => {
  for (let i = 0; i < a.length; i++) if (a[i] !== b[i]) return a[i] > b[i];
  return false;
};

/** 이 칸이 집합의 그 칸과 같은 자리인가 — key 가 같고 이름이나 뜻(hint, 심을 때 복사된다)이 같다. */
const sameSlot = (g: LiveGroup, d: GroupDef) =>
  g.key === d.key && (sameName(g.name, d.name) || (!!g.hint && sameName(g.hint, d.hint)));

/** 지금 묶음과 **가장 많이 겹치는** 집합(같은 자리 2개 이상) — 사람이 이름을 고치거나 칸을 더해도 나머지 칸은 원래 집합의 낱말로
 *  판정하려고(서버 이름 규칙 전용). 같은 자리는 key 가 같고 이름이나 **뜻**이 같은 칸이다 — 이름을 둘 고쳐도 심을 때 복사된 뜻으로
 *  옛 판을 알아본다. 동점이면 ① 지금 묶음 key 중 그 집합에 없는 것이 적은 쪽 ② 칸 수가 적은 쪽. */
export function closestSet(groups: ReadonlyArray<LiveGroup>): GroupSet | null {
  let best: GroupSet | null = null;
  let bestRank: [number, number, number] = [1, -Infinity, -Infinity];
  for (const def of ALL_SETS) {
    const score = def.groups.filter((d) => groups.some((g) => sameSlot(g, d))).length;
    if (score < 2) continue;
    const foreign = groups.filter((g) => !def.groups.some((d) => d.key === g.key)).length;
    const rank: [number, number, number] = [score, -foreign, -def.groups.length];
    if (!best || lexGreater(rank, bestRank)) { best = def; bestRank = rank; }
  }
  return best;
}

/** 집합의 가르는 기준 — 판정 질문 + 카테고리는 대부분이 가는 칸 + 고루 걸치면 본업 칸(+ 경계 예시). */
export function groupRuleLine(def: GroupSet): string {
  const fb = def.groups.find((g) => g.key === def.fallback)?.name ?? def.fallback;
  return `가르는 기준: ${def.ask} ${categoryRule(fb)}${def.note ? ` 경계 예: ${def.note}.` : ""}`;
}

/** 카테고리를 칸에 넣는 규칙 — 집합을 알아보든 못 알아보든 같은 문장이다(받침 칸 이름만 다르다).
 *  «대부분이 해당하는 칸 → 정말 고루 걸치면 받침» 두 단계뿐이다. 칸별 개수로 가르는 단계는 두지 않는다 — 2턴은 0개에서 시작해
 *   칸마다 하나씩 만들므로 늘 동수가 되고, 만드는 순서에 따라 답이 갈린다. */
function categoryRule(fallbackName: string): string {
  return `카테고리는 이름이 아니라 그 안에 모일 자료 대부분이 해당하는 칸에 둔다 — 회의록·주간 보고·그 밖의 자료처럼 종류로 나눈 서랍도, ` +
    `채널·행사·스터디·거래처 하나를 통째로 담은 카테고리도 내용이 대부분 한 칸이면 그 칸이다. ` +
    `어느 칸에도 딱 맞지 않거나 정말 고루 걸치면 «${fallbackName}». 칸이 비어도 된다 — 칸을 채우려고 카테고리를 만들지 않는다.`;
}

/** 집합을 못 알아볼 때(사람이 이름을 고쳤다)의 기준 — 칸마다 붙은 뜻(없으면 이름)으로 고르고, 받침은 서버와 같은 칸. */
export function genericRuleLine(groups: ReadonlyArray<LiveGroup>): string {
  const fbKey = groupKeyForName("", groups);
  const fb = groups.find((g) => g.key === fbKey)?.name ?? groups[0]?.name ?? "";
  return `가르는 기준: 칸마다 붙은 한 줄 뜻(뜻이 없으면 이름)으로 고른다. ${categoryRule(fb)}`;
}

/** 리브 지시문·스킬에 그대로 싣는 한 덩어리 — 묶음 목록과 가르는 기준.
 *  ⚠ 입력은 DB 에 저장된 묶음이어도 된다(사람이 이름을 고쳤을 수 있다) — 그때는 집합을 못 알아보므로 genericRuleLine. */
export function groupSetPromptLines(set: ReadonlyArray<{ key: string; name: string; hint?: string | null }>): string[] {
  const def = setMatching(set);
  return [
    ...set.map((g) => `  - \`${g.key}\` **${g.name}**${g.hint ? ` — ${g.hint}` : ""}`),
    `  ${def ? groupRuleLine(def) : genericRuleLine(set)}`,
  ];
}

