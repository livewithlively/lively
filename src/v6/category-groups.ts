//
//  ── 이름은 직무마다 다르다 ───────────────────────────────────────────────────
//  축은 같아도 부르는 말은 그 사람 것이어야 한다 — 학생에게 «거래» 라고 하지 않는다(원준 지적 2026-09-12).
//  key 는 `g1`·`g2`·`g3` 로 고정한다: 사람이 이름을 바꿔도 카테고리가 가리키는 값은 그대로 남는다.
//
//  ── 키는 **처음 설정 2단의 화면 라벨** 이다 ──────────────────────────────────
//  처음 설정은 2단 답을 화면에 보인 라벨 그대로 보낸다(web/v2/onboarding.ts: `S.job = 라벨`).
//  그래서 이 표의 키도 라벨이다. 옛 판(직무 9종)으로 답한 사람이 남아 있으므로 그 이름들도 별칭으로 남긴다.

/** 묶음이 덮는 갈래. 이름은 바뀌어도 이 셋은 안 바뀐다(덮음 증명의 기준). */
export type GroupPrinciple = "own" | "traded" | "received";

export const GROUP_PRINCIPLES: readonly GroupPrinciple[] = ["own", "traded", "received"] as const;

/** 둘에 걸쳐 보일 때의 전순서(앞이 이긴다) — 상대가 있으면 traded, 그 다음 received, 나머지가 own. */
export const PRINCIPLE_TIE_BREAK: readonly GroupPrinciple[] = ["traded", "received", "own"] as const;

export interface GroupDef {
  /** 저장되는 key(`g1`·`g2`·`g3`) — 사람이 이름을 바꿔도 이 값은 안 바뀐다. */
  key: string;
  /** 화면 이름. 사람이 고칠 수 있다. */
  name: string;
  /** 이 묶음이 덮는 갈래. 집합 안에서 겹치지 않고, 합치면 셋 전부다. */
  covers: GroupPrinciple[];
  /** 한 줄 뜻 — 화면 설명과 리브 지시문에 그대로 쓴다. */
  hint: string;
}

