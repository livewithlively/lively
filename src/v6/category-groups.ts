/**
 * 이 사람이 받을 세 칸 — 2단 답이 먼저, 없으면 1단(무대), 그래도 없으면 default.
 *  ⚠ 어느 경로로 와도 **셋을 다 덮는 집합**이 나온다. 「기타」는 어느 집합에도 없다.
 */
export function groupSetFor(stage?: string | null, job?: string | null): GroupDef[] {
  const j = String(job ?? "").trim();
  if (j && GROUP_SETS[j]) return GROUP_SETS[j];
  if (j && JOB_ALIAS[j] && GROUP_SETS[JOB_ALIAS[j]]) return GROUP_SETS[JOB_ALIAS[j]];
  const s = String(stage ?? "").trim();
  const byStage = STAGE_FALLBACK[s];
  if (byStage && GROUP_SETS[byStage]) return GROUP_SETS[byStage];
  return GROUP_SETS.default;
}

