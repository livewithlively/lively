//   (category-group-store.ts planGroupPlacement).
//  ① 지금 묶음과 가장 많이 겹치는 집합(closestSet — key 가 같고 이름이나 심을 때 복사된 뜻이 같은 칸)을 찾는다.
//  ② 사람이 이름을 고치거나 더한 칸이 먼저: 카테고리 이름에 그 칸 이름의 낱말이 들어 있으면 그 칸.
//  ③ 집합과 같은 자리인 칸들: 집합의 낱말을 전순서대로 대 본다.
//  ④ 아무것도 안 맞으면 그 집합의 받침 칸(본업 칸) — 그 key 가 지금 없으면(지웠다) 화면 순서상 첫 묶음.
//  집합을 하나도 못 알아보면 ②(모든 칸) → 화면 순서상 첫 묶음.
/** 카테고리 이름 → 넣을 묶음 key. 묶음이 0개면 null(옛 판 — 넣을 곳이 없다).
 *  ⚠ groups 는 화면 순서(sort→key)대로 와야 한다. */
export function groupKeyForName(name: string | null | undefined, groups: ReadonlyArray<LiveGroup>): string | null {
  if (!groups.length) return null;
  const n = String(name ?? "").trim();
  const def = closestSet(groups);
  //  같은 자리(이름이나 뜻이 같다)는 집합의 낱말로, 그중 이름까지 같은 칸만 «그대로» — 이름을 고친 칸은 그 이름 낱말이 먼저다.
  const same = def ? new Set(def.groups.filter((d) => groups.some((g) => sameSlot(g, d))).map((d) => d.key)) : new Set<string>();
  const kept = def
    ? new Set(def.groups.filter((d) => groups.some((g) => g.key === d.key && sameName(g.name, d.name))).map((d) => d.key))
    : new Set<string>();
  if (n) {
    for (const g of groups) {
      if (kept.has(g.key)) continue;
      if (nameTokens(g.name).length && nameRe(g.name).test(n)) return g.key;
    }
    if (def) for (const k of def.order) if (same.has(k) && def.words[k]?.test(n)) return k;
  }
  //  받침 칸 key 가 지금 있으면(이름을 고쳤어도 같은 자리다) 그 칸, 지웠으면 화면 순서상 첫 묶음.
  if (def && groups.some((g) => g.key === def.fallback)) return def.fallback;
  return groups[0].key;
}
