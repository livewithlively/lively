/** 무대(stage) → 직무 집합. 직무를 안 골랐거나 모르는 값일 때 그 다음으로 본다. */
const STAGE_FALLBACK: Record<string, string> = {
  student: "학생",
  academy: "연구·대학원",
  solo: "1인 사업",
  company: "default",
};

/**
 * 이 사람이 받을 묶음 집합 — 직무가 먼저, 없으면 무대, 그래도 없으면 default.
 *  ⚠ 어느 경로로 와도 **다섯 원칙을 다 덮는 집합**이 나온다. 「기타」는 어느 집합에도 없다.
 */
export function groupSetFor(stage?: string | null, job?: string | null): GroupDef[] {
  const j = String(job ?? "").trim();
  if (j && GROUP_SETS[j]) return GROUP_SETS[j];
  const s = String(stage ?? "").trim();
  const byStage = STAGE_FALLBACK[s];
  if (byStage && GROUP_SETS[byStage]) return GROUP_SETS[byStage];
  return GROUP_SETS.default;
}

/** 리브 지시문·스킬에 그대로 싣는 한 덩어리 — 묶음 목록과 둘 이상에 맞을 때의 순서.
 *  ⚠ 입력은 `covers` 가 없어도 된다 — 지시문은 DB 에 저장된 묶음(사람이 이름을 고쳤을 수 있다)을 싣기 때문이다. */
export function groupSetPromptLines(set: Array<{ key: string; name: string; hint?: string | null }>): string[] {
  return [
    ...set.map((g) => `  - \`${g.key}\` **${g.name}**${g.hint ? ` — ${g.hint}` : ""}`),
    "  둘 이상에 맞으면 이 순서로 고른다: 지켜야 할 조항·기준이 핵심이면 그 묶음 → 금액·지표가 핵심이면 그 묶음 →" +
      " 남의 자료를 모아 둔 것이면 그 묶음 → 상대와 오간 것이 핵심이면 그 묶음 → 나머지는 «내가 만든 것» 쪽.",
  ];
}
