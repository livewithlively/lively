// 카테고리 묶음(#1631) — **화면에서만 2단**. 데이터는 1단 그대로다.
//
//  ── 무엇이 묶음인가 ──────────────────────────────────────────────────────────
//  지식은 여전히 카테고리 **하나**에만 속한다. 묶음은 그 카테고리들을 화면에서 갈라 보여 주는 이름표일 뿐이고,
//  분류기 후보에도, 증류기 목적지(`target_category`)에도, 검색·소환에도 **들어가지 않는다.**
//  그래서 묶음이 틀려도 지식은 한 건도 안 움직인다 — 화면에서 한 칸 옆에 보일 뿐이고 사람이 옮기면 끝이다.
//
//  ⚠ 이건 2026-09-03 에 걷어낸 `space`(business/product/system)의 부활이 아니다. 그건 **분류의 층**이었고
//   (분류기가 `match_spaces` 로 좁혔다) 사람이 고를 이유가 없는 칸이었다. 여기 묶음은 **표시의 층**이고,
//   직업·직무에서 파생돼 그 사람 말로 붙으며, 사람이 이름을 바꾸고 옮길 수 있다.
//
//  ── 왜 룰베이스인가 (원준 2026-09-12) ────────────────────────────────────────
//  «각각의 직업·직군마다 MECE 하게 3~5개의 상위 카테고리를 룰베이스로 만들어서 **어떠한 지식이 생성되더라도
//   절대로 그 밖에 들어가지 않게**» — 즉 「기타」 묶음을 두지 않는다. 그러려면 묶음 집합이 그 사람 일의
//   전면을 덮어야 하고, 그 덮음을 **말이 아니라 구조로** 보장해야 한다.
//
//  ── 덮음을 증명하는 법: 다섯 원칙 ────────────────────────────────────────────
//  모든 묶음 집합은 아래 다섯 원칙의 **분할**이다(빠짐 없음 · 겹침 없음). 직무마다 이름과 묶는 방식만 다르다.
//   make     내가 만든 것        기획·설계·작업물·산출물·템플릿
//   exchange 주고받은 것         회의·메일·채팅·합의·요청·응대 기록
//   money    숫자와 돈           지표·보고·견적·청구·정산·비용
//   rule     지켜야 할 것        계약·규정·표준·절차·마감 규칙
//   learn    바깥에서 얻은 것    조사·논문·시장·경쟁·레퍼런스
//  집합마다 `covers` 의 합집합이 다섯 전부이고 서로 겹치지 않는다 — 이 불변식은 테스트가 지킨다
//  (category-groups.test.ts). 그래서 «어디에도 안 맞는 자료» 가 정의상 없다.
//
//  ── 둘 이상에 맞을 때 (전순서) ───────────────────────────────────────────────
//  rule > money > learn > exchange > make.
//   «지켜야 할 조항·기준이 핵심이면 규칙 → 금액·지표가 핵심이면 숫자와 돈 → 남의 자료를 모아 둔 것이면
//    바깥 → 상대와 오간 것이 핵심이면 주고받은 것 → 나머지는 내가 만든 것.»
//  리브 지시문과 `liv-distill` 스킬이 이 문장을 그대로 싣는다.

/** 묶음이 덮는 일의 갈래. 이름은 바뀌어도 이 다섯은 안 바뀐다(덮음 증명의 기준). */
export type GroupPrinciple = "make" | "exchange" | "money" | "rule" | "learn";

export const GROUP_PRINCIPLES: readonly GroupPrinciple[] = ["make", "exchange", "money", "rule", "learn"] as const;

/** 둘 이상에 맞을 때의 전순서(앞이 이긴다). */
export const PRINCIPLE_TIE_BREAK: readonly GroupPrinciple[] = ["rule", "money", "learn", "exchange", "make"] as const;

export interface GroupDef {
  /** 저장되는 key — 사람이 이름을 바꿔도 이 값은 안 바뀐다(카테고리가 이 값을 가리킨다). */
  key: string;
  /** 화면 이름. 사람이 고칠 수 있다. */
  name: string;
  /** 이 묶음이 덮는 원칙. 집합 안에서 서로 겹치지 않고, 합치면 다섯 전부다. */
  covers: GroupPrinciple[];
  /** 한 줄 뜻 — 화면 설명과 리브 지시문에 그대로 쓴다. */
  hint: string;
}

