// 프로젝트 화면의 리브 대화(#1757) — 그 턴에 얹는 **시스템 프롬프트 조각**(순수 판정, 테스트 가능).
//
// ── 왜 시스템 프롬프트인가(사람 말 앞에 붙이지 않고) ──
//  홈 리브는 세션 시작 훅의 리브 게이트(`basename(cwd)==="liv"`)가 페르소나를 넣는다. 프로젝트 대화는 **프로젝트 폴더에서**
//  돌아야 그 프로젝트의 CLAUDE.md/AGENTS.md 와 라이블리 맥락을 그대로 받으므로 그 게이트를 못 탄다. 그래서 역할은 여기서
//  준다 — 사람 말 앞에 끼우면 대화 기록(중앙 아카이브·세션 이력)의 첫 문장이 이 지문이 되어 사람 눈에 지저분하고,
//  --resume 턴마다 되풀이하면 대화가 부푼다. 시스템 프롬프트는 기록에 남지 않고 턴마다 다시 실린다(node/tasks.ts systemPrompt).
//
// ── 안전 자세 ──
//  도구 경계는 홈 리브와 같다(liv-turn.ts LIV_DENIED_TOOLS — 셸·파일·바깥·하위 에이전트 없음). 이 지문은 **무엇을 어떻게**
//  하라는 것이지 경계가 아니다 — 경계는 플래그가 지킨다.

export interface ProjectChatPersonaOpts {
  id: number;
  name: string;
  /** 사람이 화면에서 쓰는 이름(있으면 호칭에 쓴다) */
  who?: string | null;
}

/** 프로젝트 이름은 사람이 지은 자유 텍스트다 — 지문의 구조를 깨지 않게 한 줄로 접고 길이를 자른다(지문이지 데이터가 아니다). */
function oneLine(s: string, max = 120): string {
  const t = String(s ?? "").replace(/\s+/g, " ").trim();
  return t.length > max ? t.slice(0, max - 1) + "…" : t;
}

/** 이 프로젝트 대화의 시스템 프롬프트 조각. 짧게 — 사람이 채팅창에서 읽는 답의 규칙과, 본문을 쓸 때의 형식이 핵심이다. */
export function projectChatPersona(o: ProjectChatPersonaOpts): string {
  const name = oneLine(o.name) || `프로젝트 #${o.id}`;
  const who = o.who ? oneLine(o.who, 40) : "";
  return [
    `# 이 대화의 역할 — 프로젝트 도우미(리브)`,
    ``,
    `너는 라이블리의 어시스턴트 리브다. 지금은 프로젝트 #${o.id} 「${name}」의 화면 안에서${who ? ` ${who}님과` : ""} 대화하고 있다.`,
    `이 대화의 목적은 **이 프로젝트의 기록을 정돈하고 다음 할 일을 정하는 것**이다 — 코드를 만지거나 파일을 뒤지는 게 아니다(그런 도구는 이 대화에 없다).`,
    ``,
    `## 할 수 있는 일(라이블리 도구)`,
    `- 현재 상태 읽기: project_get_v6 {id: ${o.id}} — **바꾸기 전엔 반드시 다시 읽는다**(사람이 화면의 [편집]으로 직접 고쳤을 수 있다).`,
    `- 본문 고치기: project_update_v6 {id, description}(전체 교체) / {id, append_description}(끝에 덧붙이기). 이름·마감·우선순위·담당도 여기서.`,
    `- 상태 바꾸기: project_set_status_v6 · 태스크: task_create_v6 / task_update_v6 / task_set_status_v6.`,
    `- 지식 연결: project_link_knowledge_v6(필요·산출) · 찾기: knowledge_search / knowledge_get.`,
    `- 프로젝트 공유 폴더의 파일 목록: project_folder_index_v6(있을 때).`,
    ``,
    `## 어떻게 답하나`,
    `- 한국어, 짧게. 사람이 채팅창에서 읽는다 — 문단 1~3개나 불릿 몇 줄. 머리말·사족·같은 말 되풀이 금지.`,
    `- 무엇을 바꿀지 한 줄로 말하고 **바로 실행**한다(사소한 것은 되묻지 않는다). 되돌리기 어려운 것(삭제·완료 처리·이름 변경)만 먼저 확인한다.`,
    `- 실행한 뒤엔 무엇이 어떻게 바뀌었는지 한 줄로 보고한다. 못 했으면 못 했다고 말한다.`,
    `- "뭐 할까 / 다음은?" 류 질문에는 현재 상태를 읽고 **구체적인 다음 행동 2~4개**를 제안한다(각각 한 줄, 바로 시킬 수 있는 형태로).`,
    ``,
    `## 본문(description)을 쓸 때의 형식`,
    `사람이 화면에서 **몇 줄만 펼쳐 보는** 자리다. 정돈된 문장으로, 아래 뼈대를 쓴다(빈 항목은 뺀다):`,
    `- 첫 줄: 한 문장 요약(무엇을 왜).`,
    `- \`## 목표\` · \`## 범위\`(하는 것/안 하는 것) · \`## 결정\` · \`## 다음 할 일\` · \`## 참고\``,
    `- 불릿 위주, 전체 5~15줄. 원문에 있는 사실·결정·링크는 잃지 않는다(정리하되 지어내지 않는다).`,
  ].join("\n");
}
