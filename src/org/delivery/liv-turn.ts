// 리브 대화 턴(#1631 v1) — 헤드리스 한 번 실행을 "채팅 한 턴"으로 쓰기 위한 **순수 판정**.
//  스폰·tail 은 호출부(capability)가 하고, 여기서는 무엇을 어떤 자세로 돌릴지만 정한다(테스트 가능한 축).
//
// ── 왜 이 파일이 따로 있나 ──
// 위탁(delegate)은 사람이 안 보는 배치라 승인을 우회한다. 리브는 **사람이 화면에서 보고 있는 대화형**이라
// 그 자세를 그대로 쓰면 안 된다. 그런데 "안전하게 만드는 법"이 직관과 달라서, 그 지식이 코드 한 자리에
// 있어야 한다 — 아래 실측이 그것이다.
//
// ── ⚠ 실측 (2026-08-14, claude 2.1.232 · 각 1회 실제 실행) ──
//  프롬프트 "Bash 로 `echo hi` 를 실행해 줘" 를 세 자세로 돌린 결과:
//    · `--allowedTools Read`        → **Bash 가 그대로 실행됨**(exit 0, result="hi")
//    · `--permission-mode plan`     → **Bash 가 그대로 실행됨**(exit 0, result="hi")
//    · `--disallowedTools Bash`     → **막힘**. 매달리지 않고 exit 0, 모델이 "이 세션에는 Bash 도구가 없다"고 답함
//  ⇒ `--allowedTools` 는 경계가 아니라 **자동승인 목록**이다(있으면 안 묻고 실행 / 없어도 실행은 된다).
//    실제 경계는 `--disallowedTools` 뿐이고, 다행히 **fail-safe** 다 — 도구가 세션에서 사라질 뿐
//    승인 프롬프트로 매달리지 않는다. 매달림은 리브에서 가장 나쁜 실패다(턴이 안 끝나고 화면은 빈 채로 멎는다).
//
// ── ⚠ 거부 목록의 약점을 알고 쓴다 ──
// 거부 목록은 **새 도구가 생기면 기본 허용**이라 시간이 지나면 샌다. 허용 목록이 더 안전한 모양이지만
// 위 실측대로 허용 목록은 경계가 아니다 — 그래서 가진 축으로 최선을 다하되, 목록이 비면 아예 안 띄운다
// (빈 거부 목록 = 안전선 없음 = 우회와 같다. 그건 조용히 넘어가면 안 되는 상태다).

/** 리브 세션에서 **없애는** 도구. 이 목록이 리브의 안전선 전부다(위 실측 참조).
 *  남기는 것: 라이블리 MCP 도구(`mcp__lively__*` — 설정·수집기·분류축·묻기/올리기)와 `Skill`.
 *  리브가 하는 일은 라이블리 설정이지 그 기계를 만지는 것이 아니다. */
export const LIV_DENIED_TOOLS: readonly string[] = [
  // 기계를 만지는 것 — 리브에게 필요 없고, 사람 앞에서 승인 없이 돌면 안 되는 것들
  "Bash", "BashOutput", "KillShell",
  "Write", "Edit", "NotebookEdit",
  // 파일 읽기 — 리브는 사람 컴퓨터·서버 파일을 뒤지지 않는다(자료는 올리기로 받는다: me_liv_ask_upload)
  "Read", "Glob", "Grep",
  // 바깥으로 나가는 것 — 리브가 대화 내용을 외부로 보낼 길을 만들지 않는다
  "WebFetch", "WebSearch",
  // 하위 에이전트 — 거부 목록이 안 물려 안전선이 그대로 뚫린다(자식은 부모 제한을 상속하지 않는다)
  "Task",
];

/** claude 세션 id 는 **UUID 여야 한다**(`--session-id <uuid>` — 2.1.232 실측 문구).
 *  아무 문자열이나 넣으면 그 자리에서 죽는데, 헤드리스라 사람에겐 "아무 말도 안 나옴"으로 보인다. */
const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

export interface LivTurnOpts {
  /** 이 대화의 세션 uuid. 첫 턴은 이 id 로 세션을 만들고, 이후 턴은 같은 id 를 이어받는다. */
  sessionId: string;
  /** 이어가는 턴인가(false = 이 대화의 첫 턴). */
  resume: boolean;
}

/** 리브 한 턴의 하네스 플래그. taskScript 의 flags 인자로 그대로 들어간다(공백 join).
 *  ⚠ 이 배열의 값은 **전부 코드가 만든 것**이다 — 사람이 친 텍스트는 프롬프트 파일에만 있고 여기 안 온다.
 *   (그래서 셸 인용이 필요 없다. 그 전제가 깨지면 이 함수부터 다시 봐야 한다.) */
export function livTurnArgs(o: LivTurnOpts): string[] {
  if (!UUID_RE.test(o.sessionId)) {
    throw new Error(`리브 세션 id 는 UUID 여야 합니다: ${o.sessionId}`);
  }
  if (LIV_DENIED_TOOLS.length === 0) {
    // 빈 목록은 "제한 없음"이라 우회와 같아진다. 조용히 그렇게 되게 두지 않는다.
    throw new Error("리브 거부 도구 목록이 비어 있습니다 — 안전선 없이 리브를 띄우지 않습니다");
  }
  // ⚠ `--disallowedTools` 는 가변인자다(<tools...>). 뒤에 오는 첫 `--플래그` 에서 끊긴다 —
  //  taskScript 의 claude 문자열이 이 flags 바로 뒤에 `--output-format` 을 놓으므로 안전하게 끊긴다.
  //  이 순서가 바뀌면 뒤 인자가 도구 이름으로 먹힌다 → 그 회귀를 테스트가 고정한다.
  return [
    "--disallowedTools", ...LIV_DENIED_TOOLS,
    // 글자 단위 진행(#1665) — 이게 없으면 사람은 20초 동안 **빈 화면**을 본다(문단이 완성돼야 한 덩이로 온다).
    //  ⚠ 대가: 조각이 줄마다 실려 stream.jsonl 이 10배 가까이 커진다. tail 은 오프셋으로 이어 읽으니
    //   증분 비용은 그대로고, 늘어난 건 그 턴의 파일 크기뿐이다(턴 폴더는 대화가 끝나면 쓸모가 없다).
    //  ⚠ 그리고 조각을 이어붙인 글은 뒤따르는 완성본(assistant/text)과 **글자까지 똑같다**(실측 2026-08-15).
    //   화면이 둘 다 그리면 답이 두 번 나온다 — 그 규칙은 web/liv-chat.ts 가 지킨다.
    "--include-partial-messages",
    o.resume ? "--resume" : "--session-id", o.sessionId,
  ];
}
