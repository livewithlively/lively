// 홈 화면에 무엇을 띄우나 — 대시보드인가 리브인가(#1631).
//
// **왜 토글이 아닌가**: 리브가 가장 필요한 사람은 리브를 켤 줄 모르는 사람이다. 그리고 새 워크스페이스의
//  대시보드는 어차피 비어 있다(프로젝트 0·세션 0·작업로그 0). 대시보드 위젯에는 이미 반대 기준이 있다 —
//  "조직이 그 기능을 실제로 쓸 때만 값이 차는 위젯은 기본 배치에 자리를 주지 않는다"(#1232). 리브는 정반대라
//  **비어 있을수록 필요하다.** 그래서 사람이 켜는 게 아니라 상태가 정한다.
//
// **왜 서버가 정하나**: 화면이 자기 판정을 가지면 AI(리브)와 다른 답을 한다. 온보딩이 이미 같은 결론에
//  도달했다 — 상태의 SoT 는 서버 함수이고 화면은 표면일 뿐이다(#850). 여기도 같다.
//
// 순수 함수라 조회(무엇이 성숙인가)와 갈라 둔다 — 성숙 판정은 온보딩·파이프라인이 바뀌면 함께 바뀌지만
//  **"무엇을 띄우나"의 규칙은 그와 무관하게 고정**이고, 그 규칙이 틀리면 사람이 홈을 잃는다.

export type LivHomeMode =
  | "login"      // 리브를 띄워야 하는데 못 띄운다 — 먼저 AI 로그인을 안내한다
  | "liv"        // 홈 전체가 리브
  | "dashboard"; // 종전 대시보드

export interface LivHomeInput {
  /**
   * 이 사람이 AI(클로드 등)에 로그인돼 있나. **`null` 은 '모름'이다** — 프로브를 못 돌렸을 때 `false` 로
   * 적으면 화면이 거짓말한다(#1541 이 노드 상태에서 같은 결론에 도달했다). 모른다고 사람을 가두지 않는다.
   */
  claudeLoggedIn: boolean | null;
  /** 사람이 명시적으로 고른 값. 고른 적 없으면 null. */
  choice: "liv" | "dashboard" | null;
  /** 워크스페이스가 굴러가는 상태인가(온보딩 + 파이프라인이 실제로 도는가). */
  mature: boolean;
}

export interface LivHomeDecision { mode: LivHomeMode; reason: string }

/**
 * 홈에 무엇을 띄울지 정한다.
 *
 * 규칙은 위에서부터 먼저 맞는 것:
 *  1. **사람이 대시보드를 골랐으면 대시보드.** 사람의 선택이 상태를 이긴다 — 여기가 뒤집히면 "내가 껐는데
 *     자꾸 뜬다"가 되고, 그건 기능이 아니라 고장으로 읽힌다.
 *  2. **성숙했으면 대시보드**(사람이 리브를 고른 게 아니라면). 리브는 필요할 때만 자리를 잡는다.
 *  3. 여기까지 왔으면 리브를 띄우려는 상황이다. **로그인이 확실히 안 됐으면** 리브가 아무 일도 못 하니
 *     로그인 안내를 띄운다. 리브를 못 띄우는데 리브 화면을 여는 건 빈 화면을 주는 것과 같다.
 *  4. 그 외 → 리브.
 *
 * ⚠ 성숙 판정이 오르내려도 홈이 흔들리면 안 된다 — 그건 이 함수가 아니라 **호출자가 `choice` 를 박아** 막는다
 *  (한 번 대시보드로 넘어가면 사람이 되돌리기 전엔 그대로). 여기서 이력을 들고 있으면 순수함이 깨진다.
 */
export function livHomeMode(input: LivHomeInput): LivHomeDecision {
  const { claudeLoggedIn, choice, mature } = input;
  if (choice === "dashboard") return { mode: "dashboard", reason: "사람이 대시보드를 골랐습니다." };
  if (mature && choice !== "liv") return { mode: "dashboard", reason: "워크스페이스가 굴러가고 있어 대시보드를 띄웁니다." };
  if (claudeLoggedIn === false) {
    return { mode: "login", reason: "리브를 띄우려면 AI 로그인이 먼저 필요합니다." };
  }
  return { mode: "liv", reason: choice === "liv" ? "사람이 리브를 골랐습니다." : "워크스페이스에 아직 손볼 것이 남아 있습니다." };
}
