// 감사·호출 로그에 남길 SQL 에서 값(리터럴)만 지운다 — 구조는 보존, PII 잔존 방지(#705).
//  로그는 재실행되지 않으므로 '값만 가리면' 충분 → 파싱 실패 걱정 없는 정규식 기반(fail-safe).
//  대상: 작은따옴표 문자열('' 이스케이프 포함) · 달러-인용($tag$…$tag$) · 10자리 이상 연속숫자
//        (전화·계좌·카드·주민 bare). 연도·LIMIT·소규모 id·숫자 접미 테이블명(…_0210005)은 보존.
//  한계(모두 안전측): E-string 백슬래시 이스케이프는 리터럴이 쪼개져도 내용은 가려짐(유출 X).
export function scrubSqlLiterals(sql: string): string {
  if (typeof sql !== "string" || sql.length === 0) return sql;
  return sql
    .replace(/\$([A-Za-z0-9_]*)\$[\s\S]*?\$\1\$/g, () => "$$?$$") // 달러-인용 문자열
    .replace(/'(?:[^']|'')*'/g, () => "'?'") // 작은따옴표 문자열('' 이스케이프 포함)
    .replace(/\d{10,}/g, () => "?"); // 10자리+ 연속숫자(전화·계좌·주민 bare)
}
