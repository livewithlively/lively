/** 이번 주기에 무엇을 보낼까 — 내용을 실은 `state` 인가, 나이만 되돌리는 `beat` 인가. */
export type PushKind = "state" | "beat";

/**
 * 관측에 성공한 주기에 보낼 것(순수).
 *
 * ⚠ **관측에 실패한 주기는 여기 오지 않는다.** 호출부(`agent.pushState`)의 catch 가 그 경우를 삼키고
 *  아무것도 보내지 않는다 — 그게 fail-closed 의 자리다. 이 함수에 «안 보낸다» 라는 답이 없는 것은 그래서다.
 */
export function statePushKind(o: { force: boolean; changed: boolean; tracked: number }): PushKind {
  if (o.force || o.changed) return "state";
  //  위탁 태스크를 보는 중이면 같은 주기에 taskdone 을 얹어야 하므로 내용을 실어 보낸다(종전 계약).
  if (o.tracked > 0) return "state";
  return "beat";
}

/**
 * 박동을 받은 게이트웨이가 그 노드의 스냅샷 나이를 되돌려도 되나(순수).
 *
 * ⚠ 스냅샷이 **아직 없으면 안 된다.** 박동은 «지난번에 보낸 그 목록이 지금도 그대로» 라는 뜻인데,
 *  보낸 적이 없으면 가리킬 목록이 없다. 그때 나이를 0으로 만들면 «본 적 없는 것»이 신선해지고,
 *  판정이 빈 스냅샷으로 소유를 넘긴다 — `agent.pushState` 의 strict 규율이 막으려던 바로 그 사고다.
 */
export function beatRefreshes(prev: { ts: number } | null | undefined): boolean {
  return !!prev;
}
