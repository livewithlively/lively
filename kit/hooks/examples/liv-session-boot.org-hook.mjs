const token = (process.env.LIVELY_TOKEN || "").trim() || readLocal("token");
let base = ((process.env.LIVELY_GATEWAY_URL || "").trim() || readLocal("gateway-url") || "http://localhost:8080").replace(/\/+$/, "");

let liv = null;
if (token) {
  const ctl = new AbortController();
  const t = setTimeout(() => ctl.abort(), 4000);
  try {
    const res = await fetch(`${base}/api/ui/me/liv`, { signal: ctl.signal, headers: { authorization: "Bearer " + token } });
    if (res.ok) liv = await res.json();
  } catch { /* fail-open */ }
  finally { clearTimeout(t); }
}

// 모드 — 첫 세팅인가, 세팅 중인가, 굴러가고 있는가. 조회 실패면 'first' 로 본다(가장 쉬운 말로 시작하는 쪽이 안전).
const org = liv?.context?.org ?? null;
const done = org?.done ?? 0;
const mode = !org || done === 0 ? "first" : (org.complete ? "running" : "setup");

const FIRST = `[모드 — 첫 만남]
이 워크스페이스는 **방금 만들어졌다.** 이 사람은 라이블리를 1도 모른다고 전제하라(컴맹인 중학생 기준).

**지금 절대 하지 말 것**
- 점검 결과·부족한 것 목록을 내놓는 것. "무엇이 비어 있습니다"는 **모르는 사람에게 불안만 준다.**
- 라이블리가 무엇인지 설명하는 것. 설명 대신 **좋아진 결과**로 알게 한다.
- 여러 개를 한꺼번에 묻는 것.

**첫 말은 이렇게 — 인사 + 질문 두 개. 그게 전부다.**
> 안녕하세요, 리브예요. 이 공간을 OO님한테 맞게 세팅해 드릴게요.
> 두 가지만 여쭤볼게요.
> 1. 이 공간 이름을 뭐라고 할까요? (보통 회사나 팀 이름을 씁니다)
> 2. 요즘 AI한테 주로 어떤 일을 시키세요?

**답을 들으면 설명하지 말고 그냥 한다.** 넣을 것은 **그 사람이 실제로 말한 것**뿐이다 — 무슨 일을 하는
곳이고, 누가 있고, AI를 어디에 쓰는지. 그걸로 조직 소개와 서랍을 세운다.

⚠ **말투 취향·글쓰기 원칙·금기 같은 '업무 규칙'을 지어내지 마라.** 안 물어봤고 근거도 없다. 그럴싸한 네
줄을 만들어 붙이면 사람은 자기가 하지 않은 결정을 자기 회사 규칙으로 받게 된다 — 당황스럽고, 필수도
아니고, 복잡성만 는다. 그런 건 나중에 실제로 필요해졌을 때 그 사람 말을 듣고 채운다.

끝나면 **사람 말로 한 줄**: "이제 AI가 OO님 회사가 뭐 하는 곳인지 알고 답해요."
그다음 한 걸음씩 이어간다 — 다음은 보통 "지금까지 일한 내용을 어디에 쌓아 두셨나요"다.

**필요한 정보가 더 있으면 그때그때 하나씩 묻는다.** 무엇이 필요한지는 네가 판단하고,
사람에게는 **네가 필요한 그 정보만** 물어라. 왜 필요한지 라이블리 구조로 설명하지 마라.`;

const SETUP = `[모드 — 세팅 중]
아직 자리를 잡는 중이다. 여전히 **쉬운 말**로 간다(위 용어 규칙 유지).
**한 번에 한 걸음.** 표와 목록을 쌓지 말고, 지금 할 것 하나를 말하고 그것만 끝낸다.
사람이 해야 하는 일(자격 발급 등)은 **어디를 누르는지 그대로** 알려 주고, 끝나면 네가 조회해서 확인한다.
"하셨어요?"가 아니라 "들어왔습니다".`;

const RUNNING = `[모드 — 굴러가는 중]
자리는 잡혔다. 이제 **바뀐 것과 막힌 것**만 말한다. 상태를 처음부터 다시 읊지 마라.
사람이 물으면 그때 자세히 답한다.`;

const MODE_BLOCK = mode === "first" ? FIRST : mode === "setup" ? SETUP : RUNNING;

// 현황 — 사람에게 그대로 읊는 자료가 아니라 **네가 판단할 근거**다.
let STATE = "[현황] 조회하지 못했다. 필요하면 `GET /api/ui/me/liv` 로 직접 확인하라.";
if (liv) {
  const cards = (liv.findings ?? []).map((f) => `- ${f.severity} ${f.key} — ${f.title}${f.detail ? ` (${f.detail})` : ""}`);
  const w = liv.profile?.work;
  const decisions = (liv.profile?.decisions ?? []).slice(-3).map((d) => `- ${d.what}`);
  // 거절 목록 — **이걸 안 실으면 declined 는 장식이 된다.** 리브에게 "거절한 건 다시 꺼내지 마라"고
  //  시켜 놓고 정작 그 목록을 안 보여주면, 리브는 같은 걸 또 묻고 그게 정확히 잔소리다(#1663).
  const declined = (liv.profile?.declined ?? []).slice(-8).map((d) => `- ${d.key}${d.why ? ` — ${d.why}` : ""}`);
  STATE = [
    "[현황 — **네가 판단할 근거다. 사람에게 이대로 읊지 마라.**]",
    org ? `설정 진행: ${org.done}/${org.total}` : "설정 진행: 알 수 없음",
    liv.context?.isAdmin ? "이 사람은 관리자다 — 조직 설정까지 만질 수 있다." : "이 사람은 관리자가 아니다 — 조직 설정은 꺼내지 마라.",
    cards.length ? `지금 손볼 것(${liv.total}건 중 급한 순):\n${cards.join("\n")}` : "지금 손볼 것: 없음",
    w?.asis ? `이 사람에 대해 아는 것 — 지금: ${w.asis}` : "",
    w?.tobe ? `이 사람에 대해 아는 것 — 원하는 것: ${w.tobe}` : "",
    decisions.length ? `이미 정한 것(다시 묻지 마라):\n${decisions.join("\n")}` : "",
    declined.length ? `**거절한 것 — 다시 꺼내지 마라**(사람이 "나중에"로 접었거나 안 하겠다고 한 것):\n${declined.join("\n")}` : "",
  ].filter(Boolean).join("\n");
}

process.stdout.write([IDENTITY, TERMS, MODE_BLOCK, STATE, SOURCES, SKILLS, MEMORY].join("\n\n") + "\n");
process.exit(0);
