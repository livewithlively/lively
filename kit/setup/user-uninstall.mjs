// (4) rc 의 lively 관리 블록 제거 — LIVELY_TOKEN + 번들 Node PATH(#355). local-bin 블록은 claude 소유라 보존.
function uninstallRcBlock() {
  const candidates = [".zshrc", ".bashrc", ".bash_profile", ".profile"].map((f) => join(HOME, f));
  let total = 0;
  for (const rc of candidates) {
    if (!existsSync(rc)) continue;
    let cur; try { cur = readFileSync(rc, "utf8"); } catch { continue; }
    let next = cur; const hits = [];
    for (const [b, e, label] of [[RC_BEGIN, RC_END, "LIVELY_TOKEN"], [PATH_NODE_BEGIN, PATH_NODE_END, "PATH(node)"]]) {
      const r = stripSentinel(next, b, e); if (r.had) { next = r.text; hits.push(label); }
    }
    if (!hits.length) continue;
    next = next.replace(/\s+$/, "") + "\n";
    const short = rc.replace(HOME, "~");
    if (DRY) { log(`  [dry-run] ${short} — ${hits.join("+")} 센티넬 블록 제거 예정(나머지 보존)`); total++; continue; }
    backup(rc, "zshrc.uninstall.bak");
    writeFileSync(rc, next);
    log(`  ✓ ${short} — ${hits.join("+")} 센티넬 블록 제거(나머지 보존)`);
    total++;
  }
  if (total === 0) log("  · ~/.zshrc(및 형제 rc) — lively 관리 블록 없음(이미 제거됨/미설치)");
  return total;
}

// 하네스 자산(스킬·서브에이전트·커맨드) 제거 — materialize 된 파일은 ~/.lively 밖(~/.claude|.codex/{skills,agents,commands})이라
//  ~/.lively 삭제만으론 고아가 된다(deregisterClaudeMcp 와 같은 부류 — 트리 밖 상태의 명시적 역연산). 매니페스트에 lively 가
//  심은 것만 기록돼 있어 그 파일만 surgical 제거(멤버 본인 스킬 보존). 심링크 통과 거부. ~/.lively 트래시 이전에 호출해야 함(매니페스트가 거기 있음).
function uninstallHarnessAssets(harness) {
  const mpath = join(LIVELY, "managed-harness-assets.json");
  let manifest;
  try { manifest = JSON.parse(readFileSync(mpath, "utf8")); } catch { return; }
  if (!manifest || typeof manifest !== "object") return;
  const section = manifest[harness];
  if (!section || typeof section !== "object") return;
  const ids = Object.keys(section);
  if (!ids.length) return;
  if (DRY) { log(`  [dry-run] ${harness} 하네스 자산 ${ids.length}개 제거 예정(${ids.join(", ")})`); return; }
  let removed = 0;
  for (const id of ids) {
    const entry = section[id];
    const f = entry && entry.file;
    if (!f) continue;
    if (!/[/\\](skills|agents|commands)[/\\]/.test(f)) continue; // 방어 — 자산 경로 패턴 밖(매니페스트 변조)은 삭제 안 함
    try {
      let isLink = false; try { isLink = lstatSync(f).isSymbolicLink(); } catch { /* 파일 없음 */ }
      if (!isLink) rmSync(f, { force: true });
      if (entry.kind === "skill") { const d = dirname(f); try { if (existsSync(d) && !lstatSync(d).isSymbolicLink() && readdirSync(d).length === 0) rmdirSync(d); } catch { /* 비-빈/경합 시 보존 */ } }
      removed++;
    } catch { /* fail-soft */ }
  }
  try { delete manifest[harness]; writeFileSync(mpath, JSON.stringify(manifest, null, 2)); } catch { /* */ }
  log(`  ✓ ${harness} 하네스 자산 ${removed}개 제거`);
}

// (5) ~/.lively 제거 — 기본 휴지통 이동, --purge 면 하드 삭제.
function removeLivelyDir() {
  if (!existsSync(LIVELY)) { log("  · ~/.lively 없음 — 건너뜀"); return; }
  if (PURGE) {
    if (DRY) { log("  [dry-run] ~/.lively 하드 삭제 예정(--purge — 복구 불가)"); return; }
    rmSync(LIVELY, { recursive: true, force: true }); log("  ✓ ~/.lively 하드 삭제(--purge — 복구 불가)"); return;
  }
  const stamp = new Date().toISOString().replace(/[:.]/g, "-").replace("T", "_").replace("Z", "");
  const trash = join(HOME, `.lively.removed-${stamp}`);
  if (DRY) { log(`  [dry-run] ~/.lively → ${trash.replace(HOME, "~")} 이동 예정(되돌릴 수 있음 · --purge 면 하드삭제)`); return; }
  try { renameSync(LIVELY, trash); }
  catch { cpSync(LIVELY, trash, { recursive: true }); rmSync(LIVELY, { recursive: true, force: true }); }
  log(`  ✓ ~/.lively → ${trash.replace(HOME, "~")} 이동(되돌리려면: mv "${trash}" "${LIVELY}")`);
}

// 설치 하네스 감지(센티넬/훅 존재). rc 블록 존재도 함께 본다.
function detect() {
  const out = { claude: false, codex: false, rc: false };
  const sp = join(HOME, ".claude", "settings.json");
  if (existsSync(sp)) { try { const h = (JSON.parse(readFileSync(sp, "utf8")).hooks) || {}; out.claude = Object.values(h).some((es) => Array.isArray(es) && es.some((e) => Array.isArray(e?.hooks) && e.hooks.some((x) => String(x?.command || "").includes(LIVELY_HOOK_MARK)))); } catch { /* */ } }
  const cp = join(CODEX, "config.toml");
  if (existsSync(cp)) { try { const t = readFileSync(cp, "utf8"); out.codex = t.includes("lively-managed") && t.includes("[mcp_servers.lively]"); } catch { /* */ } }
  for (const f of [".zshrc", ".bashrc", ".bash_profile", ".profile"]) { const rc = join(HOME, f); if (existsSync(rc)) { try { const t = readFileSync(rc, "utf8"); if (t.includes(RC_BEGIN) || t.includes(PATH_NODE_BEGIN)) { out.rc = true; break; } } catch { /* */ } } }
  return out;
}

function main() {
  log(`▶ lively 제거 (발행물 동봉 제거기 — HOME=${HOME === homedir() ? "~" : HOME})${DRY ? "  [DRY-RUN — 변경 없음]" : ""}${PURGE ? "  [--purge]" : ""}`);
  log("  (uninstall = 영구 제거. 일시 off 는 incognito: env LIVELY_OFF=1 — 다름.)");
  const d = detect();
  const want = harnessArg === "all" ? ["claude", "codex"] : [harnessArg];
  if (!d.claude && !d.codex && !d.rc && !existsSync(LIVELY)) {
    log("\n✓ lively 가 이 머신에 설치되어 있지 않습니다 — 제거할 것이 없습니다(no-op)."); return;
  }
  log(`\n[1] 하네스 감지: claude=${d.claude ? "o" : "x"} codex=${d.codex ? "o" : "x"} (대상=${want.join(",")})`);
  if (want.includes("claude")) { if (d.claude) { uninstallClaudeSettings(); uninstallAutoApprove(); deregisterClaudeMcp(); deregisterExtraMcp(); uninstallHarnessAssets("claude"); } else log("  · Claude — lively 미설치, 건너뜀"); }
  if (want.includes("codex")) { if (d.codex) { uninstallCodexConfig(); uninstallCodexAgents(); deregisterCodexMcp(); uninstallHarnessAssets("codex"); } else log("  · Codex — lively 미설치, 건너뜀"); }
  // 공유 자산(~/.lively + LIVELY_TOKEN export)은 claude·codex 공용 — codex 블록은 /.lively/hooks/* 참조 + LIVELY_TOKEN 인증.
  //  --harness 로 한쪽만 제거했는데 다른 하네스가 아직 설치됐으면 공유 자산을 지우면 그 하네스가 깨진다 → 보존(설치 하네스가 0 일 때만 제거).
  const othersStillInstalled = (d.claude && !want.includes("claude")) || (d.codex && !want.includes("codex"));
  if (othersStillInstalled) {
    const remain = [d.claude && !want.includes("claude") ? "claude" : null, d.codex && !want.includes("codex") ? "codex" : null].filter(Boolean).join(",");
    log("\n[2] 셸 rc(LIVELY_TOKEN·번들 Node PATH 블록) — 보존(다른 하네스가 아직 설치됨 — 공유 자산 유지)");
    log("\n[3] ~/.lively 공유 자산 — 보존(다른 하네스가 아직 lively 를 사용 중 — 그 하네스 보호)");
    log(`  · 남은 하네스(${remain})까지 제거하려면 --harness all 로 다시 실행하세요.`);
  } else {
    log("\n[2] 셸 rc(LIVELY_TOKEN·번들 Node PATH 블록) 정리"); uninstallRcBlock();
    log("\n[3] ~/.lively 공유 자산 제거" + (PURGE ? "(--purge: 하드 삭제)" : "(기본: 휴지통 이동, 되돌릴 수 있음)")); removeLivelyDir();
  }
  log("\n✓ lively 제거 완료." + (DRY ? " (dry-run — 아무것도 변경하지 않았습니다.)" : othersStillInstalled ? " (지정 하네스만 제거 — 공유 자산은 남은 하네스를 위해 유지됨.)" : ""));
  if (!DRY && !othersStillInstalled) {
    log("  · 새 터미널을 열면 LIVELY_TOKEN export 가 사라집니다(현 셸: unset LIVELY_TOKEN).");
    log("  · 다음 claude/codex 세션부터 컨텍스트·훅이 더 이상 주입되지 않습니다.");
    if (!PURGE) log("  · 되돌리려면 ~/.lively.removed-* 를 ~/.lively 로 되돌리고 setup 을 재실행하세요.");
  }
}

