#!/usr/bin/env node
// 발행물 동봉 user-level **제거기** (self-contained · 제품 kit 미의존 — user-install.mjs 의 역연산).
//   ※ kit(workflow-std)의 adapters/*/uninstall.mjs + setup/uninstall.mjs 가 하는 일을, 발행물 자산만으로 재현.
//   ※ generator/build-context.mjs publish() 가 이 파일을 setup/ 에 복사해 넣는다(소스는 kit, 발행물은 사본).
//
// uninstall = 머신에서 lively 셋업을 **영구 제거**(오프보딩/정리/하드리셋).
//   ≠ incognito(LIVELY_OFF=1): incognito 는 설치 유지·훅만 일시 off(클린룸). uninstall 은 실제로 떼어낸다(기본 휴지통 이동).
//
// 하는 일(전부 idempotent · surgical · 백업 먼저 · LLM/모델 호출 없음):
//  (1) ~/.claude/settings.json  ← lively 훅 항목만 제거(command 에 ".lively/hooks/" 포함). tmux/기타 키 보존. + claude mcp remove lively --scope user
//  (2) ~/.codex/config.toml     ← lively-managed 센티넬 블록(BEGIN..END, [mcp_servers.lively]+[[hooks.*]])만 제거. 사용자 키 보존.
//  (3) ~/.codex/AGENTS.md        ← install 이 통째 덮어쓴 org-context. 백업 후 제거.
//  (4) ~/.zshrc(및 형제 rc)      ← LIVELY_TOKEN 센티넬 블록 제거. 나머지 보존.
//  (5) ~/.lively/               ← 기본 휴지통 이동(~/.lively.removed-<stamp>, 되돌릴 수 있음). --purge 면 하드 삭제.
//
// 사용법: node setup/user-uninstall.mjs [--dry-run] [--purge] [--harness claude|codex|all] [--yes]
//   (보통은 uninstall-mac.sh 가 호출. 직접 실행해도 동일.)
// 샌드박스/테스트: env LIVELY_HOME=<dir> 로 HOME 리다이렉트(라이브 보호). 미지정 시 os.homedir().

import {
  readFileSync, writeFileSync, existsSync, mkdirSync, copyFileSync, renameSync, rmSync, cpSync, lstatSync, readdirSync, rmdirSync,
} from "node:fs";
import { homedir } from "node:os";
import { join, dirname } from "node:path";
import { execFileSync } from "node:child_process";

const HOME = process.env.LIVELY_HOME || homedir();
const LIVELY = join(HOME, ".lively");
const CODEX = join(HOME, ".codex");

const args = process.argv.slice(2);
const DRY = args.includes("--dry-run");
const PURGE = args.includes("--purge");
const getOpt = (n) => { const i = args.indexOf(n); return i !== -1 ? args[i + 1] : null; };
const harnessArg = (getOpt("--harness") || "all").toLowerCase();
const log = (s) => console.log(s);

const LIVELY_HOOK_MARK = ".lively/hooks/";
// install 의 센티넬 리터럴(역연산이므로 정확히 일치). 현재 + 옛(harness-kit) BEGIN 둘 다 인식(R3 마이그레이션).
const CDX_BEGIN = "# >>> lively-managed (auto-generated by workflow-std/adapters/codex — do not edit) >>>";
const CDX_END = "# <<< lively-managed <<<";
const CDX_LEGACY_BEGINS = [
  "# >>> lively-managed (auto-generated by lively-harness-kit/adapters/codex — do not edit) >>>",
];
// AGENTS.md 센티넬(install 의 agentsMerge 와 동일 리터럴) — 이 블록만 surgical 제거, 사용자 내용 보존.
const AG_BEGIN = "<!-- >>> lively-managed org-context (auto-generated by workflow-std — do not edit) >>> -->";
const AG_END = "<!-- <<< lively-managed <<< -->";
const RC_BEGIN = "# >>> lively-managed (codex LIVELY_TOKEN) >>>";
const RC_END = "# <<< lively-managed (codex LIVELY_TOKEN) <<<";
// #355: setup 이 심는 번들 Node PATH 블록(~/.lively/runtime)도 함께 제거 — ~/.lively 삭제와 대칭.
//  local-bin 블록(# >>> lively-managed (PATH: local-bin) >>>)은 claude 소유라 의도적으로 보존한다.
const PATH_NODE_BEGIN = "# >>> lively-managed (PATH: node) >>>";
const PATH_NODE_END = "# <<< lively-managed (PATH: node) <<<";

// text 에서 [begin,end] 센티넬 블록 1개를 제거해 { text, had } 반환(END 손상 시 begin 한 줄만 제거·아래 보존).
function stripSentinel(text, begin, end) {
  const bi = text.indexOf(begin);
  if (bi === -1) return { text, had: false };
  const ei = text.indexOf(end, bi);
  let next;
  if (ei === -1) { const eol = text.indexOf("\n", bi); const after = eol === -1 ? "" : text.slice(eol + 1); next = (text.slice(0, bi) + after).replace(/\n{3,}/g, "\n\n"); }
  else next = (text.slice(0, bi) + text.slice(ei + end.length)).replace(/\n{3,}/g, "\n\n");
  return { text: next, had: true };
}

const backup = (src, name) => {
  try { mkdirSync(join(LIVELY, "backups"), { recursive: true }); copyFileSync(src, join(LIVELY, "backups", name)); return true; }
  catch { try { copyFileSync(src, src + ".uninstall.bak"); return true; } catch { return false; } }
};

// (1) ~/.claude/settings.json — lively 훅 엔트리만 제거.
function uninstallClaudeSettings() {
  const sp = join(HOME, ".claude", "settings.json");
  if (!existsSync(sp)) { log("  · ~/.claude/settings.json 없음 — 건너뜀"); return 0; }
  let cur;
  try { cur = JSON.parse(readFileSync(sp, "utf8")); }
  catch { log("  ⚠️ ~/.claude/settings.json JSON 파싱 실패 — 무수정"); return 0; }
  if (!cur || typeof cur !== "object" || Array.isArray(cur) || !cur.hooks || typeof cur.hooks !== "object") {
    log("  · ~/.claude/settings.json 에 hooks 없음 — 제거할 lively 훅 없음"); return 0;
  }
  // 핸들러 단위 surgical 제거 — 한 entry 에 lively+비-lively 훅이 섞였으면 lively 핸들러만 떼고 entry 보존.
  //  (어댑터 adapters/claude/uninstall.mjs 와 동일 알고리즘 — 단일 출처 동기화.)
  const isLivelyCmd = (h) => String(h?.command || "").includes(LIVELY_HOOK_MARK);
  let removed = 0; const next = {};
  for (const [event, entries] of Object.entries(cur.hooks)) {
    if (!Array.isArray(entries)) { next[event] = entries; continue; }
    const kept = [];
    for (const entry of entries) {
      const inner = Array.isArray(entry?.hooks) ? entry.hooks : [];
      const keptInner = inner.filter((h) => !isLivelyCmd(h));
      const dropped = inner.length - keptInner.length;
      removed += dropped;
      if (inner.length > 0 && keptInner.length === 0) continue; // entry 전부 lively → 제거
      kept.push(dropped > 0 ? { ...entry, hooks: keptInner } : entry); // 일부만 lively → 남은 핸들러 보존
    }
    if (kept.length) next[event] = kept; // 비면 이벤트 키 드롭
  }
  if (removed === 0) { log("  · ~/.claude/settings.json — lively 훅 없음(이미 제거됨/미설치). 무수정"); return 0; }
  if (DRY) { log(`  [dry-run] ~/.claude/settings.json — lively 훅 ${removed}건 제거 예정(tmux/기타 키 보존)`); return removed; }
  if (!backup(sp, "settings.json.uninstall.bak")) { console.error("✗ settings.json 백업 실패 — 중단(클로버 금지)"); process.exit(1); }
  cur.hooks = next;
  if (Object.keys(cur.hooks).length === 0) delete cur.hooks;
  writeFileSync(sp, JSON.stringify(cur, null, 2) + "\n");
  log(`  ✓ ~/.claude/settings.json — lively 훅 ${removed}건 제거(tmux/기타 키 보존, 백업됨)`);
  return removed;
}

// claude mcp remove lively — install 의 add 역연산. 자식 HOME 명시 주입(샌드박스 격리). idempotent.
function deregisterClaudeMcp() {
  const cmd = ["mcp", "remove", "lively", "--scope", "user"];
  if (DRY) { log(`  [dry-run] MCP 등록 해제 명령(미실행): HOME=${HOME} claude ${cmd.join(" ")}`); return; }
  try {
    execFileSync("claude", cmd, { stdio: ["ignore", "pipe", "pipe"], env: { ...process.env, HOME } });
    log("  ✓ claude mcp remove lively --scope user");
  } catch (e) {
    const m = String(e.stderr || e.stdout || e.message || "");
    if (/not found|no.*server|존재하지|찾을 수 없/i.test(m)) log("  · claude mcp: lively 미등록(이미 해제됨) — 건너뜀");
    else if (/command not found|ENOENT/i.test(m)) log("  ⚠️ claude CLI 미발견 — MCP 등록 해제 건너뜀(수동: claude mcp remove lively --scope user)");
    else log(`  ⚠️ claude mcp remove 경고(무시 가능): ${m.split("\n")[0]}`);
  }
}

// auto-approve 정리 — settings.json permissions.allow 에서 lively MCP 항목(mcp__lively__*)만 제거(멤버 본인 키 보존).
function uninstallAutoApprove() {
  const sp = join(HOME, ".claude", "settings.json");
  if (!existsSync(sp)) return 0;
  let cur; try { cur = JSON.parse(readFileSync(sp, "utf8")); } catch { return 0; }
  if (!cur || typeof cur !== "object" || !cur.permissions || !Array.isArray(cur.permissions.allow)) return 0;
  const next = cur.permissions.allow.filter((e) => !(typeof e === "string" && e.startsWith("mcp__lively__")));
  const removed = cur.permissions.allow.length - next.length;
  if (!removed) { log("  · ~/.claude/settings.json — lively auto-approve 항목 없음"); return 0; }
  if (DRY) { log(`  [dry-run] ~/.claude/settings.json — auto-approve(mcp__lively__*) ${removed}건 제거 예정`); return removed; }
  backup(sp, "settings.json.aa.uninstall.bak");
  cur.permissions.allow = next;
  writeFileSync(sp, JSON.stringify(cur, null, 2) + "\n");
  log(`  ✓ ~/.claude/settings.json — auto-approve(mcp__lively__*) ${removed}건 제거`);
  return removed;
}

// 추가 MCP 서버(org_mcp_server) 등록 해제 — ~/.lively/mcp-servers.json 순회 claude mcp remove(lively 는 별도). idempotent.
function deregisterExtraMcp() {
  const f = join(LIVELY, "mcp-servers.json");
  if (!existsSync(f)) { return; }
  let servers = [];
  try { const d = JSON.parse(readFileSync(f, "utf8")); servers = Array.isArray(d.servers) ? d.servers : []; } catch { return; }
  for (const s of servers) {
    const name = s && s.name;
    if (!name || name === "lively" || !/^[A-Za-z0-9_-]+$/.test(name)) continue;
    if (DRY) { log(`  [dry-run] claude mcp remove ${name} --scope user`); continue; }
    try {
      execFileSync("claude", ["mcp", "remove", name, "--scope", "user"], { stdio: ["ignore", "pipe", "pipe"], env: { ...process.env, HOME } });
      log(`  ✓ claude mcp remove ${name} --scope user`);
    } catch { /* 미등록/CLI 부재 — 무시(idempotent) */ }
  }
}

// (2) ~/.codex/config.toml — lively-managed 블록만 제거.
function codexStrip(text) {
  let bi = text.indexOf(CDX_BEGIN);
  if (bi === -1) for (const lb of CDX_LEGACY_BEGINS) { const li = text.indexOf(lb); if (li !== -1) { bi = li; break; } }
  if (bi === -1) return { user: text, had: false };
  const ei = text.indexOf(CDX_END, bi);
  if (ei === -1) {
    const eol = text.indexOf("\n", bi);
    const after = eol === -1 ? "" : text.slice(eol + 1);
    return { user: (text.slice(0, bi) + after).replace(/\n{3,}/g, "\n\n").trim() + "\n", had: true };
  }
  const user = (text.slice(0, bi) + text.slice(ei + CDX_END.length)).replace(/\n{3,}/g, "\n\n").trim();
  return { user: user ? user + "\n" : "", had: true };
}
function uninstallCodexConfig() {
  const cp = join(CODEX, "config.toml");
  if (!existsSync(cp)) { log("  · ~/.codex/config.toml 없음 — 건너뜀"); return; }
  const { user, had } = codexStrip(readFileSync(cp, "utf8"));
  if (!had) { log("  · ~/.codex/config.toml — lively 센티넬 블록 없음(이미 제거됨/미설치). 무수정"); return; }
  if (user.includes(CDX_BEGIN) || CDX_LEGACY_BEGINS.some((b) => user.includes(b)) || user.includes(CDX_END) || /^\s*\[mcp_servers\.lively\]\s*$/m.test(user)) {
    log("  ⚠️ ~/.codex/config.toml — 블록 제거 후 lively 잔재 — 무수정(수동 확인 필요)"); return;
  }
  if (DRY) { log("  [dry-run] ~/.codex/config.toml — lively-managed 블록 제거 예정 · 사용자 키 보존"); return; }
  backup(cp, "config.toml.codex.uninstall.bak");
  writeFileSync(cp, user);
  log("  ✓ ~/.codex/config.toml — lively-managed 블록 제거(사용자 키 보존, 백업됨)");
}

// (3) ~/.codex/AGENTS.md — lively-managed 센티넬 블록만 제거(사용자 글로벌 지침 보존). 센티넬 없으면 사용자 파일로 간주·보존.
