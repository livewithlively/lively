// v2/embed.ts — **끼워 넣은 판**인가(다른 라이블리 화면 안의 프레임으로 떠 있나).
//
//  왜 필요한가: 미리보기(`/preview/<id>/ui/`)도 라이블리 앱 자신이고 **주소가 같은 사이트**다. 브라우저는
//  같은 사이트면 localStorage 를 통째로 공유시키므로, 곁칸 웹 칸에 미리보기를 실으면 **안쪽 라이블리가
//  바깥의 저장값을 그대로 읽어** 바깥이 보던 탭·화면을 자기 안에 복제한다(원준 2026-08-21 신고
//  "미리보기 주소를 넣었는데 안 뜬다" — 실측하면 프레임 안 주소가 바깥의 `#/s/<세션>` 으로 끌려가 있고,
//  그 안에서 웹터미널까지 다시 붙으려 한다). 게다가 안쪽이 저장까지 하면 **바깥 사람의 탭·배치를 덮어쓴다**.
//
//  그래서 칸에 실을 때 주소에 표를 붙이고(web-url.ts), 그 표를 단 판은 **기억하지도 기억되지도 않는다** —
//  복원도 저장도 건너뛰고 주소가 가리키는 그 화면만 보여 준다.
//  ⚠ 읽기를 막는 것만으로는 모자라다. 저장을 같이 막지 않으면 안쪽에서 한 조작이 바깥으로 새어 나간다.
//
//  ⚠ 프레임 안인지를 `window.parent !== window` 로 **추측하지 않는다** — 그 조건은 남이 우리 화면을 끼워
//   넣은 경우에도 참이고, 반대로 앱의 webview 처럼 부모가 없는 임베드도 있다. 표는 **부르는 쪽이 붙인다**.
/** 주소에 붙는 표. 값이 정확히 EMBED_ON 일 때만 끼워 넣은 판으로 본다. */
export const EMBED_PARAM = 'embed';
export const EMBED_ON = '1';
/** 이 주소가 끼워 넣은 판을 가리키나 — 주소만 보고 정한다(순수 함수라 그대로 검증된다). */
export function isEmbedded(search) {
    try {
        return new URLSearchParams(String(search || '')).get(EMBED_PARAM) === EMBED_ON;
    }
    catch (_) {
        return false;
    } // 못 읽으면 **아니다** 쪽으로 — 기억을 잃는 편보다 안 잃는 편이 안전하다
}
/** 지금 이 판이 끼워 넣은 판인가. 앱 어디서든 이 한 값을 본다. */
export const EMBEDDED = (() => {
    try {
        return isEmbedded(location.search);
    }
    catch (_) {
        return false;
    }
})();
